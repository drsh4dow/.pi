import * as Arr from "effect/Array";
import * as Option from "effect/Option";
import * as Schema from "effect/Schema";
import * as Str from "effect/String";

export const Tool = Schema.Struct({
	name: Schema.String,
	description: Schema.optionalKey(Schema.String),
	input_schema: Schema.Json,
});

/** The part of an Anthropic request payload the report reads. */
export const Payload = Schema.Struct({
	model: Schema.String,
	system: Schema.Array(Schema.Struct({ text: Schema.String })),
	tools: Schema.Array(Tool),
});

export type Payload = typeof Payload.Type;

export interface Capture {
	readonly key: string;
	readonly title: string;
	readonly payload: Payload;
	/** `payload.tools` as indented JSON. */
	readonly toolsJson: string;
}

export interface Diff {
	readonly from: string;
	readonly to: string;
	readonly text: string;
}

export interface Report {
	readonly piVersion: string;
	readonly project: string;
	readonly message: string;
	readonly captures: ReadonlyArray<Capture>;
	readonly diffs: ReadonlyArray<Diff>;
}

/** The prompt pi built is the last system block. For OAuth tokens, pi-ai puts a Claude Code identity block before it. */
export const promptOf = (payload: Payload) =>
	Option.match(Arr.last(payload.system), { onNone: () => "", onSome: (block) => block.text });

const count = (pattern: RegExp) => (text: string) => Arr.length(Arr.fromIterable(Str.matchAll(pattern)(text)));

const skillCount = count(/<skill>/gu);

const contextFileCount = count(/<project_instructions /gu);

const sectionsOf = (prompt: string) => {
	const tags = Arr.fromIterable(Str.matchAll(/^<(?<name>[a-z_]+)>$/gmu)(prompt));
	const names = Arr.map(tags, (match) => match.groups?.["name"] ?? "");

	return Arr.filter(names, (name) => name !== "available_skills");
};

const codes = (names: ReadonlyArray<string>) =>
	Arr.join(
		Arr.map(names, (name) => `\`${name}\``),
		" ",
	);

const fence = (lang: string, body: string) => `\`\`\`\`${lang}\n${body}\n\`\`\`\`\n`;

const row = (label: string, captures: ReadonlyArray<Capture>, cell: (capture: Capture) => string) => {
	const values = Arr.map(captures, cell);

	return `| ${label} | ${Arr.join(values, " | ")} |`;
};

const table = (captures: ReadonlyArray<Capture>) => {
	const prompt = (capture: Capture) => promptOf(capture.payload);
	const toolNames = (capture: Capture) => Arr.map(capture.payload.tools, (tool) => tool.name);

	const lines = [
		row("", captures, (capture) => capture.key),
		`|---|${Str.repeat(Arr.length(captures))("---|")}`,
		row("Prompt size (chars)", captures, (capture) => String(prompt(capture).length)),
		row("Sections, in order", captures, (capture) => codes(sectionsOf(prompt(capture)))),
		row("API tools", captures, (capture) => codes(toolNames(capture))),
		row("Skills listed", captures, (capture) => String(skillCount(prompt(capture)))),
		row("Context files", captures, (capture) => String(contextFileCount(prompt(capture)))),
	];

	return Arr.join(lines, "\n");
};

const fullPrompt = (capture: Capture) => {
	const blocks = Arr.map(capture.payload.system, (block) => block.text);

	const lines = [
		`## Full prompt: ${capture.title}`,
		"",
		`Every system block, verbatim, in the order sent. Model \`${capture.payload.model}\`.`,
		"",
		fence("text", Arr.join(blocks, "\n\n---- next system block ----\n\n")),
		`<details><summary>Tool definitions sent to the API (${Arr.length(capture.payload.tools)})</summary>`,
		"",
		fence("json", capture.toolsJson),
		"</details>",
		"",
	];

	return Arr.join(lines, "\n");
};

const diffSection = (diff: Diff) => [`## Diff: ${diff.from} → ${diff.to}`, "", fence("diff", diff.text)];

export const render = (report: Report) => {
	const lines = [
		"# pi system prompts: stock vs ours vs delegates",
		"",
		`Generated by \`bun run prompts\` with pi ${report.piVersion}, in \`${report.project}\`.`,
		"Each prompt is the exact request payload pi built for its first turn. The capture extension aborts the run before pi sends it.",
		"",
		"- **stock**: pi with this agent dir minus what the harness ships (`SYSTEM.md`, `extensions/`, `delegates/` and the rest of `.gitignore`'s allowlist).",
		"- **root**: pi with the real agent dir.",
		`- **delegate-<name>**: each harness delegate, started by owned-work's own \`launch\`, on the task message "${report.message}"`,
		"",
		"## At a glance",
		"",
		table(report.captures),
		"",
		...Arr.flatMap(report.diffs, diffSection),
		...Arr.map(report.captures, fullPrompt),
	];

	return Arr.join(lines, "\n");
};
